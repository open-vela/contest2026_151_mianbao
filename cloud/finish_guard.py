"""判断候选人是不是在用嘴说「我答完了，结束吧」。

为什么需要它
------------
在此之前，面试**只能按到第 11 轮**才结束（`llm_service.HISTORY_FINISH_THRESHOLD`
那道阈值）。想提前收尾没有别的办法，只能硬着头皮再按几次 K1。对一个天天用的
练习工具来说，"我今天只想练 3 题"是最正常不过的需求。

端侧一个字都不用改：`next_action` 本来就是 `"continue"` / `"finish"` 两个值，
端侧只看它是不是 `"continue"`（`main.c:207`）。我们只要在云端**多一个**判定
`finish` 的来源，协议层面零变化。

为什么不用 LLM 判
-----------------
* 多一次调用 = 多十几秒（板子阻塞等着）+ 多一份钱，而这件事的判据简单到不需要模型；
* 更关键的是**它必须与历史无关**：候选人说"结束吧"就是结束，不该受前面答得好不好影响。
* 同 `reply_guard`：提示词是"劝"，这里是"闸"。

判据（四道闸，缺一不可）
------------------------
1. **整句精确匹配**白名单 —— 不用"包含匹配"。这一条是全文件最重要的设计：
   "循环结束的时候会释放资源"是一句合法的技术回答，包含"结束"；只有要求
   *整句就是*"结束"，才能把它挡在外面。
2. **长度 ≤ 20 字** —— 需要说一长串来铺垫的，都不是"说完了"的意思。
3. **不含问号** —— "结束了吗？"是提问，不是请求结束。
4. **剥掉礼貌外壳** —— "好的，我没什么问题了，谢谢老师"要先剥成"我没什么问题了"
   再比。只剥**开头语气词**和**结尾致谢**，不剥"了/吧"（"没问题了"里的"了"
   是有意义的收尾标记）。

宁可漏判不可误判
----------------
漏判的代价是"得再按一次 K1"；误判的代价是"面试被莫名打断，出一份半截报告"。
所以白名单刻意收得很紧：**含义模糊的一律不收**。具体地，
"没问题"、"可以了"、"就这样吧"、"没了"、"没有了" 这些**全部没有收录** ——
它们在技术问答里都是合法回答（"这个问题能解决吗" → "没问题"；"那服务后来呢"
→ "没了"）。要收就必须带上"问题/别的"这类明确的收尾标记。
"""
import re
import unicodedata

# ---------------------------------------------------------------- 白名单
#
# 收录标准：整句话**只能**理解为"面试可以结束了"。每条都经过上文的误判审视。
_FINISH_PHRASES = frozenset({
    # —— 直接说结束 ——
    "结束", "结束吧", "结束了", "结束面试", "结束面试吧", "面试结束",
    "我们结束吧", "那就结束吧", "那结束吧", "可以结束了", "就结束吧",
    "到此结束", "到这里结束", "就到这儿结束",
    # —— 说到这儿 ——
    "就到这儿", "就到这儿吧", "就到这儿了", "到这儿", "到这儿吧", "到这儿了",
    "就到这里", "就到这里吧", "到这里", "到这里吧", "到此为止",
    # —— 没有问题了（必须带"问题/别的"，见文件头"宁可漏判"一节）——
    "没问题了", "没什么问题了", "没有问题了", "没有什么问题了",
    "没有其他问题了", "没有别的问题了", "没别的问题了",
    "我没有问题了", "我没有其他问题了", "我没有别的问题了", "我没什么问题了",
    "我没什么要问的了", "没有要问的了", "没有什么要问的了",
    # —— 我问完了 ——
    "我问完了", "问完了", "没了别的了", "没别的了",
    # —— 英文（岗位是 AI/ML，候选人中英夹杂很常见）——
    # ⚠️ 这里的英文条目写的是**归一化之后**的样子：空格和撇号会被
    # `_PUNCT_RE` 剥掉，所以要写成 `iamdone` 而不是 `I'm done`。
    # 写成带空格的形式是一条永远匹配不上的死条目 —— 单测专门盯这件事
    # （见 test_finish_guard.py 的 TestWhitelistIsNormalized）。
    "stop", "end", "finish", "done",
    "iamdone", "imdone", "donewithit",
    "endtheinterview", "stoptheinterview",
    "thatsall", "nomorequestions", "ihavenomorequestions",
})

# 致谢：结束面试时的社交惯例，**开头和结尾都要剥**。
# "谢谢老师，我没有其他问题了。" 是致谢在前的常见说法，只剥结尾会漏掉它。
#
# ⚠️ 英文必须写成**归一化之后**的形式（`thankyou` 而不是 `thank you`）：
# 空格会被 `_PUNCT_RE` 剥掉，写成带空格的就是一条永远匹配不上的死规则
# —— 与白名单同一个坑。
_THANKS = r"(?:谢谢老师|谢谢您|谢谢你|谢谢大家|谢谢|多谢|thanks|thankyou|thanku)"

# 开头的语气词/应答词 + 致谢：纯社交填充，剥掉不影响语义。
_LEAD_RE = re.compile(r"^(?:好的|好吧|那|那么|嗯|呃|哦|噢|ok|行|行吧|" + _THANKS + r")")

# 结尾的致谢。
_TRAIL_RE = re.compile(_THANKS + r"$")

# 整句匹配前统一剥掉的：空白、各种标点。
#
# ⚠️ 全角和半角都得列：NFKC 只把**兼容字符**折成 ASCII（`，`→`,`、`！`→`!`），
# 而 `。`(U+3002)、`、`(U+3001) 不是兼容字符，NFKC 之后还是原样 —— 少列一个，
# 那条路径上就多一个"看着一样却匹配不上"的输入。`.` 就是这么漏掉的。
_PUNCT_RE = re.compile(
    r"[\s　。，、．.！？!?,;；:：…~～·\"'“”‘’（）()\[\]【】《》<>-]+"
)

# 长度上限。注意是**剥壳之后**的长度，量的是"核心那句话有多长"。
MAX_LEN = 20

# 剥壳最多来回几轮："好的，我没什么问题了，谢谢老师" 需要 开头→结尾 两轮，
# 留一点余量。不给无限循环 —— 这个函数在每次 K1 上都会被调用，行为必须可预测。
_MAX_PEEL = 3


def normalize(text) -> str:
    """归一化到"用来比对"的形式：全角转半角、去空白与标点、转小写。

    NFKC 是必须的：ASR 输出里全角 `！`、全角英文字母都很常见，不归一化就会
    出现"看着一模一样但比对失败"的鬼故事。
    """
    if not text:
        return ""
    text = unicodedata.normalize("NFKC", str(text))
    return _PUNCT_RE.sub("", text).lower()


def _peel(text: str) -> str:
    """剥掉两端的社交外壳：开头语气词/致谢、结尾致谢（可能交替，来回剥几轮）。"""
    for _ in range(_MAX_PEEL):
        before = text
        text = _LEAD_RE.sub("", text, count=1)
        text = _TRAIL_RE.sub("", text, count=1)
        if text == before:
            break
    return text


def match_reason(text) -> str:
    """命中结束请求时返回命中的那条白名单词；没命中返回 `""`。

    返回原因而不是布尔值，是为了让调用方（`llm_service`）能把它写进日志 ——
    真出现误判时，第一件要知道的事就是"它到底匹配上了哪个词"。
    """
    if not text:
        return ""

    # 闸 3：带问号的是提问，不是请求结束。必须在归一化**之前**判 ——
    # 问号会被 `_PUNCT_RE` 剥掉，剥完就再也看不出这是个问句了。
    # NFKC 是为了认全角的 `？`（ASR 输出里很常见）。
    if "?" in unicodedata.normalize("NFKC", text) or "？" in text:
        return ""

    core = _peel(normalize(text))
    if not core:
        return ""

    # 闸 2：剥壳后还剩一大串的，说明原句另有内容。
    if len(core) > MAX_LEN:
        return ""

    # 闸 1：整句精确匹配。
    return core if core in _FINISH_PHRASES else ""


def is_finish_request(text) -> bool:
    """候选人这句话是不是在请求结束面试。"""
    return bool(match_reason(text))
