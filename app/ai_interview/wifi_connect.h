/*
 * AI模拟面试官 — 开机自动联网（2026-10-27 加）
 *
 * 背景：板子断电重上电后**不会自动连回热点**（README 4.5.1 实测确认），
 * 每次演示都要手敲四条 wapi 命令 —— 产品化第一步就是把这个动作自动化。
 *
 * 凭据来源（优先级从高到低，**只存内存、不落盘**）：
 *   1) NSH 环境变量 WIFI_SSID / WIFI_PSK（本次启动有效）；
 *   2) 本次启动里串口/屏幕配置的凭据（同样只在内存）。
 *
 * ⚠️ 2026-11-03 删掉"记忆"功能：原来凭据落盘 /data/ai_interview_wifi，
 *    坏凭据（密码打错/换热点）会被记住 —— 复位、重连都自动用坏的、永远连不上、
 *    也不再问用户。现在**每次开机重新问一遍**，旧的记忆文件开机自动清除。
 *
 * 2026-10-31 起开机由 rcS 自动运行主程序，用户不必先敲 ai_interview。
 *
 * ⚠️ 仓库里**不写死任何热点凭据**（密码不进 git）。
 */
#ifndef __WIFI_CONNECT_H__
#define __WIFI_CONNECT_H__

/*
 * 尝试连接 Wi-Fi（若已配置凭据）。
 *
 * 返回：
 *    0  命令全部成功（**不等于一定连上** —— 连接结果以云端健康检查为准）；
 *   -1  未配置凭据，跳过；
 *   -2  凭据含不安全字符（空格/引号/分号等），拒绝执行；
 *   -3  有命令执行失败。
 *
 * 本函数会阻塞若干秒（ifup/renew 慢），**只允许在工作线程调用**。
 */
int wifi_connect_boot(void);

/*
 * 凭据是否已配置（环境变量或本次启动的内存配置至少有一处）。
 * 返回 1 已配置，0 未配置。启动时据此决定要不要走串口配置。
 */
int wifi_have_creds(void);

/*
 * 保存凭据到**内存**（屏幕配网页 / 串口配置用；2026-11-03 起不落盘、
 * 下次开机重新问）。返回 0 成功，-2 凭据不合法（空/含不支持字符）。
 */
int wifi_save_creds(const char *ssid, const char *psk);

/*
 * 串口配置（2026-10-31 加；2026-11-03 起**每次开机都会问**，不记忆）。
 *
 * 启动阶段直接读串口：提示输入热点名称与密码，校验后存内存。密码输入时
 * 关闭回显；直接回车跳过（之后可在屏幕右上角 Wi-Fi 重设）。
 *
 * 只允许**主线程、工作线程启动前**调用（会阻塞等待输入）。
 * 返回 0 = 已配置；-1 = 跳过/输入失败/标准输入不是终端。
 */
int wifi_serial_setup(void);

#endif /* __WIFI_CONNECT_H__ */
